#!/usr/bin/env node
/**
 * Test Gradle Configuration
 * Validates build.gradle configuration before EAS Build
 */

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

let errors = [];
let warnings = [];

console.log('🔍 Testing Gradle Configuration...\n');

// 1. Check if build.gradle exists
const buildGradlePath = path.join(process.cwd(), 'android', 'app', 'build.gradle');
if (!fs.existsSync(buildGradlePath)) {
  errors.push({
    issue: 'android/app/build.gradle not found',
    fix: 'Ensure android directory exists and build.gradle is present'
  });
  console.log('❌ android/app/build.gradle not found\n');
  process.exit(1);
}

// 2. Read and validate build.gradle
const buildGradle = fs.readFileSync(buildGradlePath, 'utf8');

// Check for entryFile configuration
if (!buildGradle.includes('entryFile')) {
  errors.push({
    issue: 'entryFile not configured in build.gradle',
    fix: 'Add entryFile configuration to react {} block'
  });
} else {
  // Check if entryFile is resolved correctly
  if (buildGradle.includes('new File(root,') || buildGradle.includes('new File(rootDir')) {
    warnings.push({
      issue: 'entryFile uses root (DirectoryProperty) - may cause constructor errors',
      fix: 'Use projectRootFile = rootDir.getAbsoluteFile().getParentFile() then new File(projectRootFile, ...)'
    });
  }
  
  // Check if entryFile is relative to project root
  if (buildGradle.includes('entryFile = file(') && !buildGradle.includes('projectRootFile')) {
    warnings.push({
      issue: 'entryFile may resolve relative to android/app instead of project root',
      fix: 'Use new File(projectRootFile, entryFileRelative) to ensure correct path'
    });
  }
}

// 3. Check if index.js exists at project root
const indexJsPath = path.join(process.cwd(), 'index.js');
if (!fs.existsSync(indexJsPath)) {
  errors.push({
    issue: 'index.js not found at project root',
    fix: 'Ensure index.js exists in project root'
  });
} else {
  console.log('✅ index.js found at project root');
}

// 4. Test Gradle configuration syntax (if gradlew exists)
const gradlewPath = path.join(process.cwd(), 'android', 'gradlew');
if (fs.existsSync(gradlewPath)) {
  console.log('🔍 Testing Gradle configuration syntax...');
  try {
    // Run gradle tasks --dry-run to validate configuration
    // This will catch syntax errors without building
    execSync(
      'cd android && ./gradlew tasks --dry-run 2>&1 | head -20',
      { 
        encoding: 'utf8',
        stdio: 'pipe',
        timeout: 30000
      }
    );
    console.log('✅ Gradle configuration syntax is valid');
  } catch (e) {
    const output = e.stdout || e.stderr || e.message || '';
    
    // Check for specific errors
    if (output.includes('Could not find matching constructor')) {
      errors.push({
        issue: 'Gradle constructor error detected',
        fix: 'Check entryFile configuration - use File object, not DirectoryProperty'
      });
    } else if (output.includes('entryFile')) {
      errors.push({
        issue: 'entryFile configuration error',
        fix: 'Verify entryFile path is correct relative to project root'
      });
    } else if (output.includes('BUILD FAILED')) {
      warnings.push({
        issue: 'Gradle build configuration has issues',
        fix: 'Review Gradle output for specific errors'
      });
    }
    
    // Only fail on actual errors, not warnings
    if (output.includes('Could not find matching constructor') || 
        output.includes('entryFile specifies file') ||
        output.includes('doesn\'t exist')) {
      console.log('❌ Gradle configuration error detected');
      console.log(output.substring(0, 500));
    } else {
      console.log('⚠️  Gradle check completed with warnings');
    }
  }
} else {
  console.log('⚠️  gradlew not found - skipping Gradle syntax check');
  console.log('   (This is normal if android folder is generated by prebuild)');
}

// 5. Validate entryFile resolution logic
console.log('\n🔍 Validating entryFile resolution...');
const projectRoot = process.cwd();
const androidAppDir = path.join(projectRoot, 'android', 'app');

// Simulate what Gradle should resolve
const entryFileRelative = 'index.js';
const projectRootFile = path.dirname(androidAppDir); // Should be project root
const expectedEntryFile = path.join(projectRootFile, entryFileRelative);
const actualIndexJs = path.join(projectRoot, 'index.js');

if (fs.existsSync(expectedEntryFile) || fs.existsSync(actualIndexJs)) {
  console.log('✅ entryFile would resolve correctly');
} else {
  errors.push({
    issue: 'entryFile resolution test failed',
    fix: 'Ensure entryFile resolves to project root/index.js'
  });
}

// Report results
console.log('\n📊 Results:\n');

if (errors.length > 0) {
  console.log('❌ ERRORS FOUND:');
  errors.forEach((err, i) => {
    console.log(`\n${i + 1}. ${err.issue}`);
    console.log(`   Fix: ${err.fix}`);
  });
  console.log('\n⚠️  Fix errors before pushing to EAS Build.\n');
  process.exit(1);
}

if (warnings.length > 0) {
  console.log('⚠️  WARNINGS:');
  warnings.forEach((warn, i) => {
    console.log(`\n${i + 1}. ${warn.issue}`);
    console.log(`   Fix: ${warn.fix}`);
  });
  console.log('\n⚠️  Review warnings - they may cause issues on EAS Build.\n');
  process.exit(0);
}

console.log('✅ All Gradle configuration checks passed!\n');
process.exit(0);

